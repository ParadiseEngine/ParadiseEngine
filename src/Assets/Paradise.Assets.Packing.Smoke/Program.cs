using Paradise.Assets.Packing;
using Paradise.Assets.Packing.Smoke;

using Zio.FileSystems;

if (args.Length != 1) throw new ArgumentException("Pass the smoke.pak generated by Paradise.Assets.Packing.Benchmarks.");
using var storage = new PhysicalFileSystem();
using var disk = new AssetPackFileSystem(storage, storage.ConvertPathFromInternal(Path.GetFullPath(args[0])));
Console.WriteLine("storage: " + await SmokeCheck.VerifyAsync(disk).ConfigureAwait(false));
Console.WriteLine("memory: " + await SmokeCheck.VerifyBytesAsync(File.ReadAllBytes(args[0])).ConfigureAwait(false));
